def split_legacy_name(value: str | None) -> dict[str, str | None]:
    parts = (value or "").split()
    if len(parts) > len(NAME_FIELDS) or any(
        not part.replace("-", "").replace("‑", "").replace("'", "").replace("’", "").isalpha()
        for part in parts
    ):
        parts = []
    return dict(zip(NAME_FIELDS, parts + [None] * (len(NAME_FIELDS) - len(parts))))
